#define CURSOR_TABLE_SIZE ((int)(sizeof(cursor_table) / sizeof(cursor_table[0])))

bool qws_cursor_bitmap(qws_cursor_shape_t id, qws_cursor_bitmap_t *out)
{
    if ((int)id < 0 || (int)id >= CURSOR_TABLE_SIZE)
        return false;
    const cursor_entry_t *e = &cursor_table[id];
    if (!e->data)
        return false;
    out->data   = e->data;
    out->mask   = e->mask;
    out->width  = e->width;
    out->height = e->height;
    out->hot_x  = e->hot_x;
    out->hot_y  = e->hot_y;
    return true;
}

bool qws_cursor_to_argb(const qws_cursor_bitmap_t *bm, uint32_t *argb_out)
{
    if (!bm || !bm->data || !bm->mask || !argb_out)
        return false;

    int stride = (bm->width + 7) / 8; /* bytes per row */
    for (int y = 0; y < bm->height; y++) {
        for (int x = 0; x < bm->width; x++) {
            int  byte_idx = y * stride + x / 8;
            int  bit_idx  = x % 8;              /* LSB-first */
            uint8_t d = (bm->data[byte_idx] >> bit_idx) & 1u;
            uint8_t m = (bm->mask[byte_idx] >> bit_idx) & 1u;
            uint32_t px;
            if (!m)
                px = 0x00000000u;               /* transparent */
            else if (d)
                px = 0xFF000000u;               /* opaque black */
            else
                px = 0xFFFFFFFFu;               /* opaque white */
            argb_out[y * bm->width + x] = px;
        }
    }
    return true;
}
